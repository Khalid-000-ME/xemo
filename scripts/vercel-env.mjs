#!/usr/bin/env node
/**
 * Build a production env file for Vercel from .env.local.
 *
 * Vercel's dashboard can import a .env file (Settings -> Environment Variables ->
 * Import .env), which means the secrets never have to be copied one by one — or
 * passed through a chat, a terminal history, or a CLI argument. The output is
 * gitignored and written with owner-only permissions.
 *
 * Values are never printed. Only variable names and whether they are set.
 *
 *   node scripts/vercel-env.mjs
 */

import { chmodSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const SOURCE = resolve(process.cwd(), ".env.local");
const OUTPUT = resolve(process.cwd(), ".env.vercel");

/** What production needs, in the order the guide lists them. */
const WANTED = [
  "DATABASE_URL",
  "DATABASE_AUTH_TOKEN",
  "GROQ_API_KEY",
  "XEMO_MODEL",
  "CREATEOS_SANDBOX_API_KEY",
  "CREATEOS_SHAPE",
  "CREATEOS_ROOTFS",
  "CREATEOS_MAX_CONCURRENT_SANDBOXES",
  "CREATEOS_AUTO_PAUSE_SECONDS",
  "STRIPE_SECRET_KEY",
  "STRIPE_PUBLISHABLE_KEY",
  "STRIPE_WEBHOOK_SECRET",
  "X402_PAY_TO",
  "X402_NETWORK",
  "X402_FACILITATOR_URL",
  "X402_COMMISSION_PRICE_USD",
  "X402_GENERATED_APP_PRICE_USD",
  "X402_SERVICE_NAME",
  "CDP_API_KEY_ID",
  "CDP_API_KEY_SECRET",
];

/**
 * Deliberately not carried over:
 *  - NEXT_PUBLIC_APP_URL is a localhost/tunnel origin; the app falls back to the
 *    production hostname Vercel injects.
 *  - STRIPE_WEBHOOK_SECRET in .env.local belongs to the local CLI listener. A
 *    deployed endpoint has its own signing secret, so it is only included when
 *    STRIPE_WEBHOOK_SECRET_PRODUCTION is set.
 */

function parse(text) {
  const out = {};
  for (const line of text.split("\n")) {
    const m = /^\s*([A-Z0-9_]+)\s*=\s*(.*)$/.exec(line);
    if (!m) continue;
    let v = m[2].replace(/\s+#.*$/, "").trim().replace(/^["']|["']$/g, "");
    if (v) out[m[1]] = v;
  }
  return out;
}

let env;
try {
  env = parse(readFileSync(SOURCE, "utf8"));
} catch {
  console.error(`\nCannot read ${SOURCE}\n`);
  process.exit(1);
}

if (env.STRIPE_WEBHOOK_SECRET_PRODUCTION) env.STRIPE_WEBHOOK_SECRET = env.STRIPE_WEBHOOK_SECRET_PRODUCTION;
else delete env.STRIPE_WEBHOOK_SECRET;

// Local dev keeps a file database; the deployment gets the remote one. They are
// stored under *_PRODUCTION so running the app locally never touches it.
if (env.DATABASE_URL_PRODUCTION) env.DATABASE_URL = env.DATABASE_URL_PRODUCTION;
if (env.DATABASE_AUTH_TOKEN_PRODUCTION) env.DATABASE_AUTH_TOKEN = env.DATABASE_AUTH_TOKEN_PRODUCTION;

const isRemoteDb = /^(libsql|https?|wss?):\/\//.test(env.DATABASE_URL ?? "");
if (!isRemoteDb) {
  // A file path on Vercel would silently lose data, so never emit one.
  delete env.DATABASE_URL;
  delete env.DATABASE_AUTH_TOKEN;
}

const lines = ["# Generated by scripts/vercel-env.mjs — import via Vercel -> Settings -> Environment Variables -> Import .env", ""];
const report = [];
for (const name of WANTED) {
  if (env[name]) {
    lines.push(`${name}=${env[name]}`);
    report.push([name, "included"]);
  } else {
    report.push([name, "MISSING"]);
  }
}

writeFileSync(OUTPUT, `${lines.join("\n")}\n`);
chmodSync(OUTPUT, 0o600);

console.log(`\n  wrote ${OUTPUT} (mode 600, gitignored)\n`);
for (const [name, state] of report) {
  console.log(`  ${state === "included" ? "ok     " : "MISSING"} ${name}`);
}

const missing = report.filter(([, s]) => s === "MISSING").map(([n]) => n);
if (missing.length) {
  console.log("\n  Missing is expected for:");
  if (missing.includes("DATABASE_URL")) console.log("   - DATABASE_URL / DATABASE_AUTH_TOKEN  (set DATABASE_URL_PRODUCTION / DATABASE_AUTH_TOKEN_PRODUCTION in .env.local)");
  if (missing.includes("STRIPE_WEBHOOK_SECRET")) console.log("   - STRIPE_WEBHOOK_SECRET  (create the deployed webhook endpoint first, then add its secret)");
}
console.log("");
